"""PDF report generation with reportlab (pure Python)."""

from .skills import skill_category
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import cm
from reportlab.lib import colors
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                TableStyle, HRFlowable)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_LEFT

ACCENT = colors.HexColor("#4f46e5")
DARK = colors.HexColor("#111827")
MUTED = colors.HexColor("#6b7280")


def _styles():
    ss = getSampleStyleSheet()

    def make(name, **kw):
        props = {"parent": ss["Normal"], "fontName": "Helvetica",
                 "textColor": DARK, "alignment": TA_LEFT}
        props.update(kw)
        st = ParagraphStyle(name, **props)
        ss.add(st)
        return st

    make("H1x", fontSize=20, leading=24, spaceAfter=4)
    make("H2x", fontSize=13, leading=17, spaceBefore=10, spaceAfter=4, textColor=ACCENT)
    make("Mutedx", fontSize=9, leading=12, textColor=MUTED)
    make("Bodyx", fontSize=10, leading=14, spaceAfter=3)
    make("Cellx", fontSize=9, leading=12)
    return ss


def _bar(pct, width=120):
    """Simple ASCII-style progress bar for tables."""
    filled = int(round(pct / 10))
    return "█" * filled + "░" * (10 - filled)


def _table(rows, widths, ss, header=True):
    data = [[Paragraph(str(c), ss["Cellx"]) for c in row] for row in rows]
    t = Table(data, colWidths=widths)
    style = [
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#e5e7eb")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f4f6")),
                  ("LINEBELOW", (0, 0), (-1, 0), 0.8, ACCENT)]
    t.setStyle(TableStyle(style))
    return t


def _build(filename, title, subtitle, sections):
    """sections: list of (heading, list_of_flowables)."""
    ss = _styles()
    doc = SimpleDocTemplate(filename, pagesize=A4,
                            leftMargin=1.6 * cm, rightMargin=1.6 * cm,
                            topMargin=1.6 * cm, bottomMargin=1.6 * cm,
                            title=title)
    story = [Paragraph(title, ss["H1x"]), Paragraph(subtitle, ss["Mutedx"]),
             Spacer(1, 6), HRFlowable(width="100%", color=ACCENT, thickness=1.2),
             Spacer(1, 8)]
    for heading, flowables in sections:
        if heading:
            story.append(Paragraph(heading, ss["H2x"]))
        if not isinstance(flowables, (list, tuple)):
            flowables = [flowables]
        story.extend(flowables)
    doc.build(story)


def kv_rows(pairs):
    return _table([[f"<b>{k}</b>", v] for k, v in pairs], [4.5 * cm, 12.5 * cm], _styles(), header=False)


def generate_job_match_report(path, job, resume, match, verdict_text):
    ss = _styles()
    rows = [["Skill", "Status", "Mentions", "Where"]]
    for r in match["required"]:
        status = "✓ matched" if r["matched"] else "✗ missing"
        rows.append([r["name"], status, str(r["count"]),
                     ", ".join(r["sections"]) or ("resume" if r["matched"] else "—")])
    for r in match["preferred"]:
        status = "✓ matched" if r["matched"] else "— not found"
        rows.append([f"{r['name']} (preferred)", status, str(r["count"]),
                     ", ".join(r["sections"]) or ("resume" if r["matched"] else "—")])

    evidence = []
    for r in match["required"] + match["preferred"]:
        if r["matched"] and r["evidence"]:
            evidence.append(Paragraph(f"<b>{r['name']}</b> — “…{r['evidence'][0]}…”", ss["Bodyx"]))
        elif not r["matched"]:
            evidence.append(Paragraph(f"<b>{r['name']}</b> — not detected anywhere in the resume.", ss["Bodyx"]))

    _build(path, "Job Match Analysis Report",
           f"Generated by ApplyLens — transparent, rule-based analysis (not an AI verdict).",
           [
               ("Job", kv_rows([("Company", job.company or "—"), ("Role", job.role or "—"),
                                ("Location", job.location or "—"),
                                ("Experience", job.experience or "—")])),
               ("Resume", kv_rows([("Version", resume.title),
                                   ("Health score", f"{resume.health_score if resume.health_score is not None else '—'} / 100 (checklist-based)")])),
               ("Coverage Summary", kv_rows([
                   ("Overall coverage", f"{match['coverage']}%"),
                   ("Required skills", f"{match['req_matched']} / {match['req_total']} matched"),
                   ("Preferred skills", f"{match['pref_matched']} / {match['pref_total']} matched"),
                   ("Verdict", verdict_text)])),
               ("Skill-by-skill", _table(rows, [5 * cm, 3 * cm, 2 * cm, 6.5 * cm], ss)),
               ("Evidence (why we said what we said)", evidence or [Paragraph("No skill evidence recorded.", ss["Bodyx"])]),
           ])


def generate_resume_report(path, resume, analysis, health, proof=None):
    ss = _styles()
    failed = [c for c in health["checks"] if not c["passed"]]
    passed = [c for c in health["checks"] if c["passed"]]

    check_rows = [["Check", "Result", "Points", "Note"]]
    for c in health["checks"]:
        check_rows.append([c["label"], "✓ pass" if c["passed"] else "✗ fail",
                           f"{c['points']}/{c['max']}", c.get("note", "")])

    skill_rows = [["Skill", "Mentions", "Found in"]] + [
        [s["name"], str(s["count"]), ", ".join(s["in_section"]) or "—"]
        for s in analysis.get("skills", [])[:25]]

    _build(path, "Resume Health Report", f"{resume.title} — checklist score, not an objective ranking.",
           [
               ("Overview", kv_rows([
                   ("Resume", resume.title), ("Words", str(analysis.get("word_count", 0))),
                   ("Skills detected", str(len(analysis.get("skills", [])))),
                   ("Checklist score", f"{health['score']} / 100 ({health['total']}/{health['max']} points)")])),
               ("Contact", kv_rows([(k, v) for k, v in analysis.get("contact", {}).items()] or [("Info", "No contact details detected.")])),
               ("Checklist detail", _table(check_rows, [7 * cm, 2 * cm, 2 * cm, 5.5 * cm], ss)),
               ("Failing checks (fix these first)",
                [Paragraph(f"• {c['label']}", ss["Bodyx"]) for c in failed] or [Paragraph("Nothing failed 🎉", ss["Bodyx"])]),
               ("Passing checks", [Paragraph(f"• {c['label']}", ss["Bodyx"]) for c in passed]),
               ("Skills detected", _table(skill_rows, [6 * cm, 2.5 * cm, 8 * cm], ss)),
               ("Education", [Paragraph(e, ss["Bodyx"]) for e in analysis.get("education", [])] or [Paragraph("Not detected.", ss["Bodyx"])]),
               ("Experience entries", [
                   Paragraph(f"<b>{e.get('title', '')}</b> ({e.get('dates', '')})", ss["Bodyx"])
                   for e in analysis.get("experience", [])] or [Paragraph("No dated experience entries detected.", ss["Bodyx"])]),
               ("Certifications", [Paragraph(c, ss["Bodyx"]) for c in analysis.get("certifications", [])] or [Paragraph("None detected.", ss["Bodyx"])]),
               *([_proofread_section(proof, ss)] if proof else []),
           ])


def _proofread_section(proof, ss):
    """Proofreader findings section: typos, date issues, tense mixing."""
    flow = []

    summary = proof.get("findings", [])
    if summary:
        flow.append(Paragraph("Summary: " + " ".join(summary), ss["Bodyx"]))
        flow.append(Spacer(1, 4))

    typos = proof.get("typos", [])
    if typos:
        rows = [["Word", "Suggestion", "Where it appears"]]
        for t in typos[:15]:
            rows.append([f"<b>{t['word']}</b>", f"→ {t['suggestion']}",
                         f"…{t['snippet']}…"])
        flow.append(_table(rows, [3.2 * cm, 3.2 * cm, 10.6 * cm], ss))
    else:
        flow.append(Paragraph("No common misspellings detected "
                              "(curated list, not a full dictionary).", ss["Bodyx"]))

    dates = proof.get("dates", {})
    date_lines = []
    for fr in dates.get("future_ranges", []):
        date_lines.append(f"<b>{fr['range']}</b> ends in {fr['end_year']} — likely a typo: “…{fr['snippet']}…”")
    for g in dates.get("suspicious_gaps", []):
        date_lines.append(f"<b>{g['range']}</b> ends before it starts: “…{g['snippet']}…”")
    for g in dates.get("gaps", []):
        date_lines.append(f"<b>{g['months']}-month gap</b> between “{g['after']}” and “{g['before']}”")
    if date_lines:
        flow.append(Spacer(1, 4))
        flow.append(Paragraph("<b>Date issues</b>", ss["Bodyx"]))
        flow.extend(Paragraph(f"• {l}", ss["Bodyx"]) for l in date_lines)
    elif dates.get("found"):
        flow.append(Spacer(1, 4))
        flow.append(Paragraph("Date ranges look consistent — no backwards ranges or year-long gaps found.", ss["Bodyx"]))

    tense = proof.get("tense", {})
    if tense.get("past_bullets") and tense.get("present_bullets"):
        flow.append(Spacer(1, 4))
        flow.append(Paragraph(
            f"<b>Tense:</b> {tense['past_bullets']} past-tense vs {tense['present_bullets']} "
            f"present-tense bullets in Experience. Past roles → past tense; current role → present tense.",
            ss["Bodyx"]))

    if not flow:
        return ("Proofreader", [Paragraph("No findings.", ss["Bodyx"])])
    return ("Proofreader — typos, dates, tense (every finding quoted)", flow)


def generate_application_summary(path, app_, job, resume, interviews):
    ss = _styles()
    iv_rows = [["Round", "When", "Mode", "Outcome"]] + [
        [i.round_name, i.scheduled_at.strftime("%d %b %Y %H:%M"), i.mode or "—", i.outcome or "Pending"]
        for i in interviews]
    _build(path, "Application Summary", f"{job.company or 'Company'} — {job.role or 'Role'}",
           [
               ("Application", kv_rows([
                   ("Company", job.company or "—"), ("Role", job.role or "—"),
                   ("Status", app_.status), ("Applied on", app_.applied_on.strftime("%d %b %Y") if app_.applied_on else "—"),
                   ("Resume used", resume.title if resume else "—")])),
               ("Interviews", _table(iv_rows, [4.5 * cm, 4.5 * cm, 3 * cm, 4 * cm], ss) if interviews
                else [Paragraph("No interviews recorded yet.", ss["Bodyx"])]),
               ("Notes", [Paragraph((app_.notes or "No notes.").replace("\n", "<br/>"), ss["Bodyx"])]),
           ])


def _contact_line(contact):
    bits = []
    for key in ("email", "phone", "location"):
        if contact.get(key):
            bits.append(contact[key])
    for key in ("linkedin", "github", "portfolio"):
        if contact.get(key):
            bits.append(contact[key])
    return "  |  ".join(bits)


def _bullets(items, ss, style="Bodyx"):
    return [Paragraph(f"• {i}", ss[style]) for i in items]


def generate_resume_document(path, resume, analysis):
    """
    Rebuild a clean, consistently formatted resume from the parsed data.
    The layout is fixed by ApplyLens; the content comes from the user's file.
    """
    ss = _styles()
    contact = analysis.get("contact", {})
    skills = analysis.get("skills", [])

    name = (contact.get("name") or resume.title).strip()
    sections = []

    header = [Paragraph(f"<b>{name}</b>", ParagraphStyle(
                  "NameX", parent=ss["H1x"], fontSize=19, leading=23, spaceAfter=2))]
    line = _contact_line(contact)
    if line:
        header.append(Paragraph(line, ss["Mutedx"]))
    sections.append(("", header))

    if analysis.get("sections", {}).get("summary"):
        text = " ".join(analysis["sections"]["summary"].split())
        sections.append(("Summary", [Paragraph(text, ss["Bodyx"])]))

    if skills:
        # group skills by category, strongest (most mentioned) first inside each group
        by_cat = {}
        for s in skills:
            cat = skill_category(s["name"])
            by_cat.setdefault(cat, []).append(s)
        rows = [[Paragraph(f"<b>{cat}</b>", ss["Cellx"]),
                 Paragraph(", ".join(s["name"] for s in items[:14]), ss["Cellx"])]
                for cat, items in sorted(by_cat.items())]
        if rows:
            t = Table(rows, colWidths=[3.6 * cm, 13.4 * cm])
            t.setStyle(TableStyle([
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                ("TOPPADDING", (0, 0), (-1, -1), 2),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                ("LINEBELOW", (0, 0), (-1, -2), 0.3, colors.HexColor("#e8e2d4")),
            ]))
            sections.append(("Skills", [t]))

    if analysis.get("experience"):
        blocks = []
        for e in analysis["experience"]:
            head = f"<b>{e.get('title') or 'Role'}</b>"
            if e.get("dates"):
                head += f" &nbsp;&nbsp;—&nbsp;&nbsp; {e['dates']}"
            blocks.append(Paragraph(head, ss["Bodyx"]))
            detail = " ".join((e.get("detail") or "").split())
            if detail:
                for chunk in _split_sentences(detail):
                    blocks.append(Paragraph(f"• {chunk}", ParagraphStyle(
                        "BulletX", parent=ss["Bodyx"], leftIndent=10,
                        bulletIndent=0, spaceAfter=1)))
            blocks.append(Spacer(1, 4))
        sections.append(("Experience", blocks))

    if analysis.get("projects"):
        sections.append(("Projects", _bullets(analysis["projects"][:8], ss)))

    if analysis.get("education"):
        sections.append(("Education", _bullets(analysis["education"][:6], ss)))

    if analysis.get("certifications"):
        sections.append(("Certifications", _bullets(analysis["certifications"][:8], ss)))

    if analysis.get("sections", {}).get("achievements"):
        text = " ".join(analysis["sections"]["achievements"].split())
        sections.append(("Achievements", [Paragraph(text, ss["Bodyx"])]))

    footer = [Paragraph(
        f"Rebuilt from “{resume.original_filename}” by ApplyLens — "
        f"fixed clean layout, parsed content.", ss["Mutedx"])]
    sections.append(("", footer))

    _build(path, name or "Resume", "Clean résumé generated from parsed data",
           sections)


def _split_sentences(text, max_len=180):
    """Split a blob of text into bullet-sized sentences/fragments."""
    import re
    parts = re.split(r"(?<=[.!?])\s+|\s*[•;]\s*", text)
    out, buf = [], ""
    for p in parts:
        p = p.strip(" -–")
        if not p:
            continue
        if len(buf) + len(p) < max_len:
            buf = (buf + " " + p).strip()
        else:
            if buf:
                out.append(buf)
            buf = p
    if buf:
        out.append(buf)
    return out[:8]


